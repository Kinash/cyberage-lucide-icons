<?php
/**
 * START OF: CyberAge Lucide icon library
 * Purpose: The single place that knows the bundled Lucide icons. It resolves an icon name
 *          (including old, renamed names) and builds the inline SVG markup that the Elementor
 *          tab and the shortcode both output.
 * Context: Called while a page renders: by the Elementor icon tab's render callback and by the
 *          [lucide] shortcode. Never called on requests that show no icons.
 * Effect: Reads assets/icons.json and assets/aliases.json once per request (lazy, cached in a
 *         static property) and returns SVG strings. Writes nothing.
 * Dependencies: assets/icons.json (name => inner SVG markup) and assets/aliases.json
 *               (old name => current name), both generated by tools/build-icons.mjs from the
 *               pinned lucide-static version. Never edit those files by hand.
 * Inputs: An icon name such as "flask-conical", with or without the "lucide-" class prefix,
 *         plus optional HTML attributes for the <svg> element.
 * Outputs: An inline <svg> string, or an empty string when the name is unknown.
 * Safety: SVG bodies come only from the bundled JSON, never from user input. Every attribute
 *         name and value passed in is escaped. Unknown names return '' instead of failing.
 * Developer note: Elementor stores icons by name inside page data, so a renamed icon must stay
 *                 resolvable through aliases.json forever. When a Lucide upgrade drops a name,
 *                 the build script's release notes say so: add it to tools/aliases-manual.json
 *                 and rebuild, never delete an alias.
 * Author: Benson Matheka
 * Email: benson.matheka@outlook.com
 * Phone: +254728121374
 */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

final class CyberAge_Lucide_Library {

	/**
	 * Current icon name => inner SVG markup, loaded on first use.
	 *
	 * @var array<string,string>|null
	 */
	private static $icons = null;

	/**
	 * Old icon name => current icon name, loaded on first use.
	 *
	 * @var array<string,string>|null
	 */
	private static $aliases = null;

	/**
	 * Load both JSON files once per request.
	 *
	 * Safety: a missing or broken file leaves an empty set, so pages render without icons
	 * rather than producing a fatal error.
	 */
	private static function load() {
		if ( null !== self::$icons ) {
			return;
		}
		$read          = static function ( $file ) {
			$path = CYBERAGE_LUCIDE_DIR . 'assets/' . $file;
			$data = is_readable( $path ) ? json_decode( (string) file_get_contents( $path ), true ) : null; // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- bundled local file, not a remote URL.
			return is_array( $data ) ? $data : array();
		};
		self::$icons   = $read( 'icons.json' );
		self::$aliases = $read( 'aliases.json' );
	}

	/**
	 * Turn any stored icon reference into a current icon name.
	 *
	 * Inputs: "flask-conical", "lucide-flask-conical" or Elementor's "lucide lucide-flask-conical".
	 * Outputs: the current name, or '' when the icon does not exist in this set.
	 */
	public static function resolve( $name ) {
		self::load();
		$name = strtolower( trim( (string) $name ) );
		$name = (string) preg_replace( '/^.*\blucide-/', '', $name );
		if ( isset( self::$icons[ $name ] ) ) {
			return $name;
		}
		return isset( self::$aliases[ $name ] ) ? self::$aliases[ $name ] : '';
	}

	/**
	 * Build the inline SVG for one icon.
	 *
	 * Inputs: $name (any form accepted by resolve()), $attributes (HTML attributes; "class" may
	 *         be a string or an array and is merged with the icon's own classes).
	 * Outputs: the <svg> string, or '' for an unknown icon.
	 * Safety: attribute names are limited to safe characters and values are escaped.
	 * Developer note: style="fill:none" must stay. Elementor colours SVG icons with the CSS
	 *                 fill property, which would turn Lucide's outline icons into solid
	 *                 shapes; the colour reaches the stroke through currentColor instead.
	 */
	public static function svg( $name, array $attributes = array() ) {
		$icon = self::resolve( $name );
		if ( '' === $icon ) {
			return '';
		}
		$class = isset( $attributes['class'] ) ? $attributes['class'] : '';
		$class = is_array( $class ) ? implode( ' ', $class ) : (string) $class;
		unset( $attributes['class'] );

		$attrs = array_merge(
			array(
				'xmlns'           => 'http://www.w3.org/2000/svg',
				'width'           => '24',
				'height'          => '24',
				'viewBox'         => '0 0 24 24',
				'fill'            => 'none',
				'stroke'          => 'currentColor',
				'stroke-width'    => '2',
				'stroke-linecap'  => 'round',
				'stroke-linejoin' => 'round',
				'aria-hidden'     => 'true',
				'focusable'       => 'false',
				'style'           => 'fill:none',
			),
			$attributes
		);

		$html = '<svg class="' . esc_attr( trim( 'lucide lucide-' . $icon . ' ' . $class ) ) . '"';
		foreach ( $attrs as $key => $value ) {
			if ( null === $value || false === $value || ! preg_match( '/^[a-zA-Z_:][a-zA-Z0-9_:.-]*$/', (string) $key ) ) {
				continue;
			}
			$html .= ' ' . $key . '="' . esc_attr( is_array( $value ) ? implode( ' ', $value ) : (string) $value ) . '"';
		}
		return $html . '>' . self::$icons[ $icon ] . '</svg>';
	}
}

