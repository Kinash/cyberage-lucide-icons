// Builds the plugin's bundled icon set from the pinned lucide-static version (tools/package.json).
//
// Writes into ../assets/:
//   icons.json    current icon name -> inner SVG markup (what the front end renders, inline)
//   aliases.json  old/renamed name -> current name (Lucide's own renames + tools/aliases-manual.json)
//   picker.json   {"icons": [...]} the list Elementor's icon picker shows (current names only)
//   editor.css    picker/editor preview: each icon drawn with a CSS mask (no icon font)
//   manifest.json version, counts and the name list, kept to compare against the next release
// and ../docs/RELEASE-NOTES-<version>.md listing added icons and any name that disappeared.
//
// Why the alias map matters: Elementor stores an icon by name in each page's data. If a Lucide
// update renames an icon, pages built earlier would lose it. Every old name keeps resolving.
//
// Run: cd tools && npm install && node build-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const LUCIDE = path.join(HERE, "node_modules/lucide-static");
const ASSETS = path.join(ROOT, "assets");
const version = JSON.parse(fs.readFileSync(path.join(LUCIDE, "package.json"), "utf8")).version;

// Current names come from icon-nodes.json; every other .svg in icons/ is an old name Lucide keeps.
const current = Object.keys(JSON.parse(fs.readFileSync(path.join(LUCIDE, "icon-nodes.json"), "utf8"))).sort();
const inner = (file) => fs.readFileSync(file, "utf8")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")
  .replace(/\s*\/>/g, "/>").replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();

const icons = {};
for (const name of current) icons[name] = inner(path.join(LUCIDE, "icons", `${name}.svg`));

// Old names: matched to the current icon with identical drawing.
const byMarkup = new Map(current.map((n) => [icons[n], n]));
const aliases = {};
const unmatched = [];
for (const f of fs.readdirSync(path.join(LUCIDE, "icons")).filter((x) => x.endsWith(".svg"))) {
  const name = f.slice(0, -4);
  if (icons[name]) continue;
  const target = byMarkup.get(inner(path.join(LUCIDE, "icons", f)));
  if (target) aliases[name] = target; else unmatched.push(name);
}
// Manual aliases: for names Lucide later drops entirely (filled in from the release notes).
const manualFile = path.join(HERE, "aliases-manual.json");
// The BOM is stripped because Windows editors (and PowerShell's utf8) often add one.
const manual = fs.existsSync(manualFile) ? JSON.parse(fs.readFileSync(manualFile, "utf8").replace(/^﻿/, "") || "{}") : {};
for (const [from, to] of Object.entries(manual)) if (icons[to]) aliases[from] = to;

// Compare with the previous release so a vanished name is never missed.
const manifestFile = path.join(ASSETS, "manifest.json");
const previous = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile, "utf8")) : null;
const known = new Set([...current, ...Object.keys(aliases)]);
const vanished = previous ? [...previous.icons, ...Object.keys(previous.aliases || {})].filter((n) => !known.has(n)) : [];
const added = previous ? current.filter((n) => !previous.icons.includes(n)) : [];

// Editor preview CSS: a small encoding (only the characters a CSS url() needs escaped) keeps the
// file about a third smaller than full URI encoding.
const enc = (s) => s.replace(/%/g, "%25").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E").replace(/"/g, "'");
const svg = (body) => `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${body.replace(/"/g, "'")}</svg>`;
const css = [
  `/* CyberAge Lucide Icons: picker and editor preview (Lucide ${version}, ISC). Generated by tools/build-icons.mjs. */`,
  ".lucide{display:inline-block;width:1em;height:1em;background-color:currentColor;-webkit-mask:var(--lucide) center/contain no-repeat;mask:var(--lucide) center/contain no-repeat;vertical-align:-0.125em}",
  // Picker tab label: Elementor spaces its tab icons with padding-inline-end:15px, which a mask
  // icon absorbs. The same gap as a margin lines "Lucide" up with the Font Awesome tabs (v1.0.1).
  ".elementor-icons-manager__tab-link .lucide{padding:0;margin-inline-end:15px;width:20px;height:20px}",
  ...current.map((n) => `.lucide-${n}{--lucide:url("data:image/svg+xml,${enc(svg(icons[n]))}")}`),
  ...Object.entries(aliases).map(([a, n]) => `.lucide-${a}{--lucide:url("data:image/svg+xml,${enc(svg(icons[n]))}")}`),
].join("\n");

fs.mkdirSync(ASSETS, { recursive: true });
fs.writeFileSync(path.join(ASSETS, "icons.json"), JSON.stringify(icons));
fs.writeFileSync(path.join(ASSETS, "aliases.json"), JSON.stringify(aliases, null, 1));
fs.writeFileSync(path.join(ASSETS, "picker.json"), JSON.stringify({ icons: current }));
fs.writeFileSync(path.join(ASSETS, "editor.css"), css + "\n");
fs.writeFileSync(manifestFile, JSON.stringify({ lucide: version, icons: current, aliases }, null, 1));
fs.copyFileSync(path.join(LUCIDE, "LICENSE"), path.join(ROOT, "LICENSE-lucide.txt"));

const notes = [
  `# Icon set: Lucide ${version}`, "",
  `- Current icons: ${current.length}`,
  `- Old names kept working (aliases): ${Object.keys(aliases).length}`,
  previous ? `- Added since Lucide ${previous.lucide}: ${added.length ? added.join(", ") : "none"}` : "- First release of the icon set.",
  vanished.length ? `- **ACTION: names no longer resolving: ${vanished.join(", ")}.** Map each to its replacement in tools/aliases-manual.json and rebuild before releasing.` : "- No icon name has disappeared.",
  unmatched.length ? `- Old names with no identical current icon (not aliased): ${unmatched.join(", ")}` : "",
].filter(Boolean).join("\n");
fs.mkdirSync(path.join(ROOT, "docs"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "docs", `RELEASE-NOTES-lucide-${version}.md`), notes + "\n");
const kb = (f) => (fs.statSync(path.join(ASSETS, f)).size / 1024).toFixed(0) + " KB";
console.log(`Lucide ${version}: ${current.length} icons, ${Object.keys(aliases).length} aliases, ${unmatched.length} unmatched, ${vanished.length} vanished | icons.json ${kb("icons.json")}, editor.css ${kb("editor.css")}`);
if (vanished.length) process.exitCode = 1;
